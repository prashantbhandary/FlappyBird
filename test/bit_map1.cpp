void setup() {
  Serial.begin(115200);
  
  // Initialize I2C with default pins (GPIO 21 = SDA, GPIO 22 = SCL for ESP32)
  Wire.begin();
  
  // Initialize display
  if(!display.begin(SSD1306_SWITCHCAPVCC, SCREEN_ADDRESS)) {
    Serial.println(F("SSD1306 allocation failed"));
    for(;;);
  }
  
  // Clear the buffer
  display.clearDisplay();
  display.display();
  
  stateStartTime = millis();
  Serial.println("Display initialized! Starting with scrolling text...");
}

void loop() {
  unsigned long currentTime = millis();
  
  // Clear display
  display.clearDisplay();
  
  if (displayState == 0) {
    // State 0: Show static image
    display.drawBitmap(0, 0, myBitmap, 128, 64, WHITE);
    
    // Check if it's time to switch from image to PM Balen
    if (currentTime - stateStartTime >= imageDisplayTime) {
      displayState = 2; // Switch to PM Balen
      stateStartTime = currentTime;
      animationFrame = 0;
      Serial.println("Image finished! Showing PM Balen...");
    }
  } else if (displayState == 1) {

    if (currentTime - stateStartTime >= lyricDisplayTime) {
      currentLyricIndex++;
      stateStartTime = currentTime;
      
      // If all lyrics shown, switch to Image
      if (currentLyricIndex >= numLyrics) {
        displayState = 0; // Switch to Image
        stateStartTime = currentTime;
        Serial.println("Lyrics finished! Showing image...");
      }
    }
    
    // Display current lyric if still in lyrics mode
    if (currentLyricIndex < numLyrics) {
      // Use large text size
      display.setTextSize(2);
      display.setTextColor(WHITE);
      
      // Center the text
      const char* currentText = lyrics[currentLyricIndex];
      int16_t x1, y1;
      uint16_t w, h;
      display.getTextBounds(currentText, 0, 0, &x1, &y1, &w, &h);
      
      // Center horizontally and vertically
      int16_t x = (SCREEN_WIDTH - w) / 2;
      int16_t y = (SCREEN_HEIGHT - h) / 2;
      
      display.setCursor(x, y);
      display.println(currentText);
    }
  } else if (displayState == 2) {
    // State 2: Show "PM Balen" with zoom animation
    unsigned long elapsed = currentTime - stateStartTime;
    
    // Zoom effect: start small and grow
    int textSize = 1;
    if (elapsed < 500) {
      textSize = 1;
    } else if (elapsed < 1000) {
      textSize = 2;
    } else {
      textSize = 2.5;
    }
    
    display.setTextSize(textSize);
    display.setTextColor(WHITE);
    
    // Center the text
    const char* pmBalen = "PM Balen";
    int16_t x1, y1;
    uint16_t w, h;
    display.getTextBounds(pmBalen, 0, 0, &x1, &y1, &w, &h);
    
    int16_t x = (SCREEN_WIDTH - w) / 2;
    int16_t y = (SCREEN_HEIGHT - h) / 2;
    
    display.setCursor(x, y);
    display.println(pmBalen);
    
    // Check if it's time to switch to lyrics
    if (elapsed >= pmBalenDisplayTime) {
      displayState = 1; // Switch back to lyrics
      currentLyricIndex = 0; // Reset to first lyric
      stateStartTime = currentTime;
      Serial.println("PM Balen finished! Restarting lyrics...");
    }
  }
  
  // Update display
  display.display();
  delay(50); // Small delay for stability
}
